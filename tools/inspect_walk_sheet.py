#!/usr/bin/env python3
"""Emit GPU cell bounds/pivots from alpha; never modifies source artwork."""
from pathlib import Path
from PIL import Image
import json
project = Path(__file__).resolve().parent.parent
# Follow the active sheets; stale UVs must never be applied to newer textures.
if (project/'assets/characters/active-retro.json').exists():
    import runpy
    runpy.run_path(str(project/'tools/inspect_retro_sheets.py'),run_name='__main__')
    raise SystemExit(0)

source = project / 'assets/characters/johnny-walk-v3.png'
with Image.open(source) as im:
    assert im.mode == 'RGBA' and im.size == (1536,1024)
    alpha=im.getchannel('A')
    cells=[]
    for n in range(8):
        ox=(n%4)*384;oy=(n//4)*512
        mask=alpha.crop((ox,oy,ox+384,oy+512)).point(lambda v:255 if v>=128 else 0)
        x1,y1,x2,y2=mask.getbbox()
        cap=mask.crop((x1,y1,x2,y1+(y2-y1)//5)).getbbox()
        pivot=x1+(cap[0]+cap[2])/2
        assert x1>0 and y1>0 and x2<384 and y2<512
        sole=[]
        for yy in range(y2-4,y2):
            sole.extend(xx for xx in range(x1,x2) if mask.getpixel((xx,yy)))
        plant=(min(sole)+max(sole)+1)/2-x1
        span=max(sole)-min(sole)+1
        cells.append({'x':ox+x1,'y':oy+y1,'w':x2-x1,'h':y2-y1,'pivot':pivot-x1,'plant':plant,'span':span})
metadata={'source':source.name,'alpha_cutoff':128,'columns':4,'rows':2,'cells':cells}
(project/'assets/characters/johnny-walk-v3.json').write_text(json.dumps(metadata,indent=2)+'\n')
header='/* Generated by tools/inspect_walk_sheet.py; source artwork is unchanged. */\n'
header+='typedef struct { int x,y,w,h; float pivot, plant, span; } JCHDCell;\nstatic const JCHDCell hd_cells[8] = {\n'
for c in cells: header+='  {%d,%d,%d,%d,%.1ff,%.1ff,%.1ff},\n'%(c['x'],c['y'],c['w'],c['h'],c['pivot'],c['plant'],c['span'])
header+='};\n'
(project/'generated/johnny_walk.h').write_text(header)
print(json.dumps(metadata,indent=2))
