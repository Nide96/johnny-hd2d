/* Geometry-only masks for the inspected Johnny contact-shadow families.
 * Regenerate with original resources; no RGBA sheet or logical pixel changes.
 */
#include "resource.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "shadow_candidates.h"
static int extended_candidate(const char *n, size_t id) {
  for (size_t i = 0; i < sizeof shadow_candidates / sizeof *shadow_candidates; ++i)
    if (id == shadow_candidates[i].id &&
        !strcmp(n, shadow_candidates[i].resource))
      return 1;
  return 0;
}
static int candidate(const char *n, size_t id) {
  if (!strcmp(n, "JOHNWALK.BMP"))
    return id != 13;
  if (!strcmp(n, "MJ_AMB.BMP"))
    return 1;
  if (!strcmp(n, "MJCOCO.BMP"))
    /* Audited full bodies: palm shaking, coconut pickup/throw and standing.
     * Detached hands, heads and torso overlays never own the ground shadow. */
    return id <= 6 || (id >= 8 && id <= 15) || (id >= 20 && id <= 23) ||
           id == 31 || id == 32 || id == 36 || id == 37;
  if (!strcmp(n, "SLEEP.BMP"))
    return id < 17 && id != 12;
  if (!strcmp(n, "MJREAD.BMP"))
    return id <= 19 || (id >= 21 && id <= 23) || (id >= 26 && id <= 30);
  if (!strcmp(n, "MJFISH1.BMP"))
    return (id >= 3 && id <= 13) || id == 16 || id == 17 || id == 20 ||
           id == 21;
  if (!strcmp(n, "MJFISH2.BMP"))
    return id == 3 || (id >= 6 && id <= 14) || id == 24;
  return extended_candidate(n, id);
}
int main(int argc, char **argv) {
  JCAssets a = {0};
  JCError e = {{0}};
  if (!jc_assets_load(&a, argc > 1 ? argv[1] : "assets/original", &e))
    return 1;
  puts("/* Geometry only, generated by tools/export_shadow_masks.c; palette "
       "index 8. */\n#ifndef JC_SHADOW_MASKS_H\n#define "
       "JC_SHADOW_MASKS_H\ntypedef struct { unsigned short y, x1, x2; } "
       "JCShadowSpan;\ntypedef struct { const char *resource; unsigned short "
       "id, w, h, start, count; } JCShadowMask;");
  FILE *records = tmpfile();
  if (!records)
    return 1;
  unsigned offset = 0;
  puts("static const JCShadowSpan jc_shadow_spans[] = {");
  for (size_t n = 0; n < a.archive.count; ++n) {
    const char *name = a.archive.files[n].name;
    size_t len = strlen(name);
    if (len < 4 || strcmp(name + len - 4, ".BMP"))
      continue;
    JCBmp b = {0};
    if (!jc_archive_bmp(&a.archive, name, &b, &e))
      return 1;
    for (size_t id = 0; id < b.count; ++id) {
      if (!candidate(name, id))
        continue;
      const JCSprite *s = &b.sprites[id];
      size_t size = (size_t)s->w * s->h;
      uint8_t *seen = calloc(size, 1), *mask = calloc(size, 1);
      int *queue = malloc(size * sizeof *queue);
      if (!seen || !mask || !queue)
        return 1;
      for (size_t k = 0; k < size; ++k) {
        if (seen[k] || s->px[k] != 8)
          continue;
        size_t head = 0, tail = 1;
        queue[0] = (int)k;
        seen[k] = 1;
        int y1 = s->h, y2 = 0, x1 = s->w, x2 = 0;
        unsigned exterior = 0, interior = 0;
        while (head < tail) {
          int p = queue[head++], x = p % s->w, y = p / s->w;
          if (x < x1) x1 = x;
          if (x > x2) x2 = x;
          if (y < y1)
            y1 = y;
          if (y > y2)
            y2 = y;
          const int dx[] = {-1, 1, 0, 0}, dy[] = {0, 0, -1, 1};
          for (int d = 0; d < 4; ++d) {
            int xx = x + dx[d], yy = y + dy[d], q = yy * s->w + xx;
            if (xx < 0 || xx >= s->w || yy < 0 || yy >= s->h || !s->px[q])
              ++exterior;
            else if (s->px[q] != 8)
              ++interior;
            if (xx >= 0 && xx < s->w && yy >= 0 && yy < s->h && !seen[q] &&
                s->px[q] == 8) {
              seen[q] = 1;
              queue[tail++] = q;
            }
          }
        }
        /* Lower external grey components, audited against cap/shorts/paper.
         * Lying poses have a lower local silhouette than upright ones. */
        int sleeping = !strcmp(name, "SLEEP.BMP");
        int extended = extended_candidate(name, id);
        float threshold =
            sleeping
                ? .40f
                : (!strcmp(name, "MJREAD.BMP") && id == 19 ? .60f : .70f);
        if (extended) threshold = .40f;
        if (tail >= 35 && y1 >= s->h * threshold &&
            y2 >= s->h - ((sleeping || extended) ? 12 : 8) &&
            (!extended || ((y2-y1+1) <= (x2-x1+1)*.80f &&
                           exterior * 3 >= interior)))
          for (size_t j = 0; j < tail; ++j)
            mask[queue[j]] = 1;
      }
      unsigned start = offset;
      for (int y = 0; y < s->h; ++y)
        for (int x = 0; x < s->w;) {
          if (!mask[y * s->w + x]) {
            ++x;
            continue;
          }
          int left = x;
          while (x < s->w && mask[y * s->w + x])
            ++x;
          printf("{%d,%d,%d},\n", y, left, x);
          ++offset;
        }
      if (offset > start)
        fprintf(records, "{\"%s\",%zu,%d,%d,%u,%u},\n", name, id, s->w,
                s->h, start, offset - start);
      free(seen);
      free(mask);
      free(queue);
    }
    jc_bmp_free(&b);
  }
  puts("};\nstatic const JCShadowMask jc_shadow_masks[] = {");
  rewind(records);
  int c;
  while ((c = fgetc(records)) != EOF)
    putchar(c);
  puts("};\n#endif");
  fclose(records);
  jc_assets_free(&a);
  return 0;
}
