#!/usr/bin/env python3
"""Measure alpha bounds for authored cells; emit UV metadata, never edit art."""
from pathlib import Path
from PIL import Image
import json
root = Path(__file__).resolve().parent.parent
# Follow the active sheets; stale UVs must never be applied to newer textures.
if (root/'assets/characters/active-retro.json').exists():
    import runpy
    runpy.run_path(str(root/'tools/inspect_retro_sheets.py'),run_name='__main__')
    raise SystemExit(0)

specs = [('poses',5,2,[0,9,10,11,12,14,15,16,17,18]),
         ('rest',4,2,list(range(8))),
         ('sleep',4,4,list(range(12))+list(range(13,17)))]
header = '/* Generated by tools/inspect_action_sheets.py; alpha cutoff 128. */\n'
for name, cols, rows, ids in specs:
    source = root / f'assets/characters/johnny-{name}-v1.png'
    im = Image.open(source)
    assert im.mode == 'RGBA' and im.size == (1536,1024)
    mask = im.getchannel('A').point(lambda x:255 if x>=128 else 0)
    cells=[]
    ybounds=[0]
    for row in range(1,rows):
        nominal=round(row*im.height/rows)
        gaps=[y for y in range(nominal-48,nominal+49)
              if not mask.crop((0,y-1,im.width,y+2)).getbbox()]
        assert gaps,(name,row,'no transparent row gutter')
        ybounds.append(min(gaps,key=lambda y:abs(y-nominal)))
    ybounds.append(im.height)
    for row in range(rows):
        y0,yend=ybounds[row:row+2]
        strip=mask.crop((0,y0,im.width,yend))
        boundaries=[0]
        for col in range(1,cols):
            nominal=round(col*im.width/cols)
            gaps=[x for x in range(nominal-48,nominal+49)
                  if not strip.crop((x-1,0,x+2,strip.height)).getbbox()]
            assert gaps, (name,row,col,'no transparent gutter')
            boundaries.append(min(gaps,key=lambda x:abs(x-nominal)))
        boundaries.append(im.width)
        for col in range(cols):
            x0,xend=boundaries[col:col+2]
            cell=strip.crop((x0,0,xend,strip.height))
            box=cell.getbbox();assert box
            x1,y1,x2,y2=box
            assert x1>0 and y1>0 and x2<cell.width and y2<cell.height,(name,row,col,box)
            cap=cell.crop((x1,y1,x2,y1+max(1,(y2-y1)//5))).getbbox()
            pivot=(cap[0]+cap[2])/2
            sole=[x for y in range(max(y1,y2-4),y2)
                  for x in range(x1,x2) if cell.getpixel((x,y))]
            cells.append(dict(sprite=ids[len(cells)],x=x0+x1,y=y0+y1,w=x2-x1,h=y2-y1,
                              pivot=pivot,plant=(min(sole)+max(sole)+1)/2-x1,
                              span=max(sole)-min(sole)+1))
    metadata=dict(source=source.name,alpha_cutoff=128,columns=cols,rows=rows,cells=cells)
    (source.with_suffix('.json')).write_text(json.dumps(metadata,indent=2)+'\n')
    header += f'static const JCHDCell hd_{"pose" if name=="poses" else name}_cells[{len(cells)}] = {{\n'
    for c in cells:
        header+='  {%d,%d,%d,%d,%.1ff,%.1ff,%.1ff},\n'%(c['x'],c['y'],c['w'],c['h'],c['pivot'],c['plant'],c['span'])
    header+='};\n'
    print(name,len(cells),'separated sprites, no opaque clipping')
(root/'generated/johnny_actions.h').write_text(header)
