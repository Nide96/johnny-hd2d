#!/usr/bin/env python3
"""Measure transparent sprite regions without changing any generated pixels."""
from pathlib import Path
from PIL import Image
import json
root=Path(__file__).resolve().parent.parent
# Follow the active sheets; stale UVs must never be applied to newer textures.
if (root/'assets/characters/active-retro.json').exists():
    import runpy
    runpy.run_path(str(root/'tools/inspect_retro_sheets.py'),run_name='__main__')
    raise SystemExit(0)

specs=[('reading','read',6,4,list(range(24))),
       ('reading-props','read_props',4,3,list(range(24,36))),
       ('reading-walk','read_walk',3,2,list(range(24,30)))]
header='/* Generated by tools/inspect_reading_sheets.py; alpha cutoff 128. */\n'
for name,table,cols,rows,ids in specs:
    version='v2' if name=='reading-walk' else 'v1'
    source=root/f'assets/characters/johnny-{name}-{version}.png'
    im=Image.open(source)
    assert im.mode=='RGBA' and im.size==(1536,1024),(source,im.mode,im.size)
    mask=im.getchannel('A').point(lambda v:255 if v>=128 else 0)
    def gutters(length,count,empty):
        bounds=[0]
        for i in range(1,count):
            mid=round(i*length/count)
            candidates=[p for p in range(mid-96,mid+97) if empty(p)]
            assert candidates,(name,i,'no transparent gutter')
            bounds.append(min(candidates,key=lambda p:abs(p-mid)))
        return bounds+[length]
    ybounds=gutters(im.height,rows,lambda y:not mask.crop((0,y-1,im.width,y+2)).getbbox())
    cells=[]
    for row in range(rows):
        y0,yend=ybounds[row:row+2]
        strip=mask.crop((0,y0,im.width,yend))
        xbounds=gutters(im.width,cols,lambda x:not strip.crop((x-1,0,x+2,strip.height)).getbbox())
        for col in range(cols):
            x0,xend=xbounds[col:col+2];cell=strip.crop((x0,0,xend,strip.height))
            box=cell.getbbox();assert box,(name,row,col,'empty cell')
            x1,y1,x2,y2=box
            assert x1>0 and y1>0 and x2<cell.width and y2<cell.height,(name,row,col,'clipped cell',box)
            cap=cell.crop((x1,y1,x2,y1+max(1,(y2-y1)//5))).getbbox()
            sole=[x for y in range(max(y1,y2-4),y2) for x in range(x1,x2) if cell.getpixel((x,y))]
            cells.append(dict(sprite=ids[len(cells)],x=x0+x1,y=y0+y1,w=x2-x1,h=y2-y1,
                              pivot=(cap[0]+cap[2])/2,
                              plant=(min(sole)+max(sole)+1)/2-x1,span=max(sole)-min(sole)+1))
    source.with_suffix('.json').write_text(json.dumps(dict(source=source.name,alpha_cutoff=128,columns=cols,rows=rows,cells=cells),indent=2)+'\n')
    header+=f'static const JCHDCell hd_{table}_cells[{len(cells)}] = {{\n'
    for c in cells:header+='  {%d,%d,%d,%d,%.1ff,%.1ff,%.1ff},\n'%(c['x'],c['y'],c['w'],c['h'],c['pivot'],c['plant'],c['span'])
    header+='};\n'
    print(name,len(cells),'cells, transparent gutters and unclipped alpha verified')
(root/'generated/johnny_reading.h').write_text(header)
