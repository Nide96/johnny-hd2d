/* Emit geometry only. No original pixels are included in generated headers. */
#include "resource.h"
#include <stdio.h>
int main(int argc, char **argv) {
  JCAssets assets = {0};
  JCBmp bmp = {0};
  JCError error = {{0}};
  if (!jc_assets_load(&assets, argc > 1 ? argv[1] : "assets/original",
                      &error) ||
      !jc_archive_bmp(&assets.archive, "MJREAD.BMP", &bmp, &error)) {
    fprintf(stderr, "%s\n", error.message);
    return 1;
  }
  if (bmp.count != 36)
    return 2;
  puts("/* Generated by tools/export_reading_bounds.c; geometry only. */\n"
       "typedef struct { int width,height,x,y,w,h; } JCReadingBounds;\n"
       "static const JCReadingBounds reading_bounds[36] = {");
  for (size_t n = 0; n < bmp.count; n++) {
    const JCSprite *s = &bmp.sprites[n];
    int x1 = s->w, y1 = s->h, x2 = -1, y2 = -1;
    for (int y = 0; y < s->h; y++)
      for (int x = 0; x < s->w; x++)
        if (s->px[y * s->w + x]) {
          if (x < x1)
            x1 = x;
          if (x > x2)
            x2 = x;
          if (y < y1)
            y1 = y;
          if (y > y2)
            y2 = y;
        }
    if (x2 < x1 || y2 < y1)
      return 3;
    printf("  {%d,%d,%d,%d,%d,%d}, /* %zu */\n", s->w, s->h, x1, y1,
           x2 - x1 + 1, y2 - y1 + 1, n);
  }
  puts("};");
  jc_bmp_free(&bmp);
  jc_assets_free(&assets);
  return 0;
}
